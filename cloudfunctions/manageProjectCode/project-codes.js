function normalizeProjectCode(value) {
  return String(value || '').trim().toUpperCase();
}

function normalizeProjectName(value) {
  return String(value || '').trim();
}

function normalizeStatus(status) {
  return status === 'disabled' ? 'disabled' : 'active';
}

function normalizeProjectCodeRecord(record = {}) {
  return {
    _id: record._id,
    project_code: normalizeProjectCode(record.project_code || record.code),
    project_name: normalizeProjectName(record.project_name || record.name),
    status: normalizeStatus(record.status),
    is_builtin: !!record.is_builtin,
    sort_order: Number(record.sort_order !== undefined ? record.sort_order : record.order) || 0
  };
}

function sortProjectCodeRecords(records = []) {
  return (records || [])
    .map(normalizeProjectCodeRecord)
    .filter(item => item.project_code)
    .sort((a, b) => {
      const orderDiff = (Number(a.sort_order) || 0) - (Number(b.sort_order) || 0);
      if (orderDiff !== 0) return orderDiff;
      return a.project_code.localeCompare(b.project_code);
    });
}

function buildProjectCodeLabel(record = {}) {
  const projectCode = normalizeProjectCode(record.project_code);
  const projectName = normalizeProjectName(record.project_name);
  return projectName ? `${projectCode} - ${projectName}` : projectCode;
}

function buildProjectCodeActions(records = []) {
  return sortProjectCodeRecords(records)
    .map(item => ({
      name: buildProjectCodeLabel(item),
      project_code: item.project_code,
      project_name: item.project_name
    }));
}

async function ensureCollection(db) {
  if (!db || typeof db.createCollection !== 'function') {
    return;
  }
  try {
    await db.createCollection('project_codes');
  } catch (error) {
    const message = String((error && error.errMsg) || error.message || '');
    if (message.includes('exists') || message.includes('已存在') || message.includes('DATABASE_COLLECTION_ALREADY_EXISTS')) {
      return;
    }
  }
}

async function loadAllProjectCodeRecords(db, pageSize = 100) {
  const collection = db.collection('project_codes');
  let skip = 0;
  let records = [];

  while (true) {
    let res;
    try {
      res = await collection.skip(skip).limit(pageSize).get();
    } catch (error) {
      if (skip === 0) {
        return [];
      }
      throw error;
    }
    const batch = res.data || [];
    records = records.concat(batch);
    if (batch.length < pageSize) {
      break;
    }
    skip += pageSize;
  }

  return records;
}

async function ensureBuiltinProjectCodes(db) {
  await ensureCollection(db);
  const collection = db.collection('project_codes');
  const existingRecords = await loadAllProjectCodeRecords(db);
  const normalizedRecords = existingRecords.map(normalizeProjectCodeRecord);
  const byCode = new Map(normalizedRecords.map(item => [item.project_code, item]));

  for (const seed of BUILTIN_PROJECT_CODE_SEEDS) {
    const existing = byCode.get(seed.project_code);
    if (existing && existing._id) {
      const needsRefresh =
        existing.project_name !== seed.project_name ||
        existing.is_builtin !== true ||
        existing.sort_order !== seed.sort_order;
      if (needsRefresh) {
        await collection.doc(existing._id).update({
          data: {
            project_name: seed.project_name,
            is_builtin: true,
            sort_order: seed.sort_order,
            updated_at: db.serverDate()
          }
        });
      }
      continue;
    }

    await collection.add({
      data: {
        project_code: seed.project_code,
        project_name: seed.project_name,
        status: seed.status,
        is_builtin: true,
        sort_order: seed.sort_order,
        created_at: db.serverDate(),
        updated_at: db.serverDate()
      }
    });
  }

  return sortProjectCodeRecords(await loadAllProjectCodeRecords(db));
}

